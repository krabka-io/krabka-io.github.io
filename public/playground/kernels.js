// ---- value rendering --------------------------------------------------------

// Render a JSON value from the kernel. `prominent` is true for the top-level
// result, which gets the large treatment; nested values render compactly.
function renderValue(value, prominent) {
  if (typeof value === "boolean") {
    return badge(String(value), value ? "kx-badge-true" : "kx-badge-false");
  }
  if (value === null || value === undefined) {
    return badge("null", "kx-badge-null");
  }
  if (typeof value === "number" || typeof value === "bigint") {
    const n = el("span", prominent ? "kx-number kx-number-big" : "kx-number");
    n.textContent = String(value);
    return n;
  }
  if (typeof value === "string") {
    return badge(value, "kx-badge-string");
  }
  if (Array.isArray(value)) {
    if (value.every(isScalar)) {
      const list = el("code", prominent ? "kx-array kx-array-big" : "kx-array");
      list.textContent = `[${value.map((v) => toJson(v, false)).join(", ")}]`;
      return list;
    }
    if (value.length > 0 && value.every(isPlainObject)) {
      return objectTable(value);
    }
    const pre = el("pre", "kx-json");
    pre.textContent = toJson(value, true);
    return pre;
  }
  if (isPlainObject(value)) {
    return keyValueTable(value);
  }
  const pre = el("pre", "kx-json");
  pre.textContent = toJson(value, true);
  return pre;
}

function keyValueTable(obj) {
  const table = el("table", "kx-kv");
  const tbody = document.createElement("tbody");
  for (const [key, val] of Object.entries(obj)) {
    const tr = document.createElement("tr");
    const th = document.createElement("th");
    th.scope = "row";
    th.textContent = key;
    const td = document.createElement("td");
    td.appendChild(renderValue(val, false));
    tr.append(th, td);
    tbody.appendChild(tr);
  }
  table.appendChild(tbody);
  return table;
}

// A list of objects becomes one row per object with the union of the keys as
// columns, so a kernel that returns e.g. a list of segments reads as a table.
function objectTable(rows) {
  const columns = [];
  for (const row of rows) {
    for (const key of Object.keys(row)) {
      if (!columns.includes(key)) columns.push(key);
    }
  }
  const table = el("table", "kx-rows");
  const thead = document.createElement("thead");
  const headRow = document.createElement("tr");
  for (const col of columns) {
    const th = document.createElement("th");
    th.scope = "col";
    th.textContent = col;
    headRow.appendChild(th);
  }
  thead.appendChild(headRow);
  const tbody = document.createElement("tbody");
  for (const row of rows) {
    const tr = document.createElement("tr");
    for (const col of columns) {
      const td = document.createElement("td");
      if (Object.prototype.hasOwnProperty.call(row, col)) {
        td.appendChild(renderValue(row[col], false));
      }
      tr.appendChild(td);
    }
    tbody.appendChild(tr);
  }
  table.append(thead, tbody);
  return table;
}

function badge(text, cls) {
  const b = el("span", `kx-badge ${cls}`);
  b.textContent = text;
  return b;
}

function isScalar(v) {
  return v === null || (typeof v !== "object" && typeof v !== "function");
}

function isPlainObject(v) {
  return v !== null && typeof v === "object" && !Array.isArray(v);
}

// ---- JSON helpers -----------------------------------------------------------

// Parse a kernel response. Where the engine supports JSON.parse source access
// (Chrome 114+, Firefox 129+, Safari 17.4+), integers outside the safe range
// are kept exact as BigInt instead of being rounded to the nearest double.
function parseResponse(text) {
  return JSON.parse(text, (_key, value, context) => {
    if (
      typeof value === "number" &&
      !Number.isSafeInteger(value) &&
      context &&
      typeof context.source === "string" &&
      /^-?\d+$/.test(context.source)
    ) {
      return BigInt(context.source);
    }
    return value;
  });
}

// JSON.stringify that also serialises BigInt (as a bare integer).
function toJson(value, pretty, indent = "") {
  if (typeof value === "bigint") return value.toString();
  if (value === undefined) return "null";
  if (value === null || typeof value !== "object") return JSON.stringify(value);
  const inner = pretty ? `${indent}  ` : "";
  const sep = pretty ? ",\n" : ",";
  const open = pretty ? "\n" : "";
  const close = pretty ? `\n${indent}` : "";
  if (Array.isArray(value)) {
    if (value.length === 0) return "[]";
    const items = value.map((v) => inner + toJson(v, pretty, inner));
    return `[${open}${items.join(sep)}${close}]`;
  }
  const entries = Object.entries(value);
  if (entries.length === 0) return "{}";
  const members = entries.map(
    ([k, v]) =>
      `${inner}${JSON.stringify(k)}:${pretty ? " " : ""}${toJson(v, pretty, inner)}`,
  );
  return `{${open}${members.join(sep)}${close}}`;
}

function kernelFromHash() {
  const hash = location.hash || "";
  if (!hash.startsWith(HASH_PREFIX)) return null;
  try {
    return decodeURIComponent(hash.slice(HASH_PREFIX.length));
  } catch {
    return null;
  }
}

