// Integers use a text input rather than type=number so that values past
// 2^53 survive as the typed digits; min / max are enforced by parseInteger and
// surfaced as a hint.
function numberInput(field) {
  const input = textInput("");
  input.inputMode = "numeric";
  const bounds = [];
  if (field.min != null) bounds.push(`min ${field.min}`);
  if (field.max != null) bounds.push(`max ${field.max}`);
  if (bounds.length > 0) input.placeholder = bounds.join(", ");
  return input;
}

function escapeHtml(s) {
  return s.replace(
    /[&<>"']/g,
    (c) =>
      ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[
        c
      ],
  );
}

// Read the kernel specs the page embeds. Throws when they are missing or not
// an array so boot() can show the reason next to the fallback text.
function readSpecs() {
  const node = document.getElementById(SPECS_ID);
  if (!node) throw new Error(`missing #${SPECS_ID} on the page`);
  const specs = JSON.parse(node.textContent);
  if (!Array.isArray(specs) || specs.length === 0) {
    throw new Error(`#${SPECS_ID} holds no kernel specs`);
  }
  return specs;
}

// ---- boot -------------------------------------------------------------------

async function boot() {
  const root = document.getElementById("krabka-kernels");
  if (!root) return;
  try {
    const specs = readSpecs();
    await init();
    new KernelExplorer(root, specs);
  } catch (err) {
    // Leave the fallback paragraph in place and say why the panel is missing.
    const note = el("p", "kx-error");
    note.innerHTML = `The kernel explorer failed to load: ${escapeHtml(
      String(err),
    )}`;
    root.appendChild(note);
    // eslint-disable-next-line no-console
    console.error("krabka kernel explorer failed to initialise", err);
  }
}

boot();
