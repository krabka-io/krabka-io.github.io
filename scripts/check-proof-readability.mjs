import assert from 'node:assert/strict';
import { obligationSummary, formulaTokens, tokenText, readableTokens } from '../public/proofs/readability.js';

assert.equal(obligationSummary('audit ensures #1', '(result = RejectSignature) = (not signature_valid)'), 'Returns RejectSignature exactly when signature_valid is false.');
assert.equal(obligationSummary('audit ensures #2', '(result = RejectHead) = (signature_valid /\\ not head_matches)'), 'Returns RejectHead exactly when signature_valid is true and head_matches is false.');
for (const formula of ['(result = Admit) = (valid /\\ seq > 0)', '(result = Admit) = (valid…)', '(result = Admit) = (true)', '(result = Admit) = (valid \\/ ready)', '(result = Admit) = ((valid))']) {
  assert.equal(obligationSummary('audit ensures #0', formula), '');
}
assert.equal(obligationSummary('call requires #0'), '');
assert.equal(obligationSummary('loop invariant #1'), '');
assert.equal(obligationSummary('unknown'), '');
const formula = '[@expl:test] (result = Done) /\\ not x \\/ y <> 0 -> true <-> false <script>';
const tokens = formulaTokens(formula);
assert.equal(tokens.map((token) => token.text).join(''), formula);
assert.equal(tokens.find((token) => token.text === '/\\').kind, 'operator');
assert.equal(tokens.find((token) => token.text === '0').kind, 'literal');
assert.equal(tokens[0].kind, 'annotation');
assert.equal(tokens.map((token) => tokenText(token, false)).join(''), formula);
const readable = formulaTokens('[@expl:x /\\ y] (x /\\ y) \\/ z <> 0');
assert.equal(readable.map((token) => tokenText(token, true)).join(''), ' (x  &  y)  ||  z  !=  0');
const comparison = "[%#saudit'2] gt_log_Int (UInt64.t'int expected_seq) 0 /\\ UInt64.t'int checkpoint_seq_high + 1 = UInt64.t'int expected_seq";
const comparisonTokens = formulaTokens(comparison);
assert.equal(comparisonTokens.map((token) => tokenText(token, false)).join(''), comparison);
assert.equal(comparisonTokens.map((token) => tokenText(token, true)).join(''), ' expected_seq > 0  &  checkpoint_seq_high + 1  ==  expected_seq');
assert.equal(tokenText(formulaTokens('[@inline:trivial]')[0], true), '[@inline:trivial]');
for (const unsupported of ["gt_log_Int (f x) y", "UInt64.t'int (f x)", "UInt64.t'int x'1"]) {
  assert.equal(formulaTokens(unsupported).map((token) => tokenText(token, false)).join(''), unsupported);
}
assert.equal(tokenText(formulaTokens('gt_log_Int')[0], true), '>');
assert.equal(formulaTokens('gt_log_Int')[0].dataType, 'integer');
assert.equal(formulaTokens('true')[0].dataType, 'boolean');
assert.equal(formulaTokens('UInt64.t')[0].dataType, 'unsigned');
assert.equal(tokenText(formulaTokens("ge_log_Int (UInt32.t'int count) 0")[0], true), 'count >= 0');
const longFormula = 'x /\\ '.repeat(1000) + 'final_condition';
assert.equal(formulaTokens(longFormula).map((token) => tokenText(token, false)).join(''), longFormula);
const pretty = (text) => readableTokens(formulaTokens(text)).map((token) => token.display).join('');
assert.equal(pretty('([@stop_split] (result = Admit) = (ready /\\ (valid \\/ retry)))'), '(\n  (returned value == Admit) == (\n    ready\n    & (\n      valid\n      || retry\n    )\n  )\n)');
assert.equal(pretty('([%#span] result = Done)'), '(returned value == Done)');
assert.equal(pretty('(a /\\ b) \\/ (c /\\ d)'), '(\n  a\n  & b\n)\n|| (\n  c\n  & d\n)');
assert.equal(pretty('x = "a ( b )"'), 'x == "a ( b )"');
assert.equal(pretty('(a /\\ b').replace(/\s/g, ''), '(a&b');
assert.equal(pretty('x = "a /\\ b  12"'), 'x == "a /\\ b  12"');
assert.equal(pretty('not a <> b /\\ x < y \\/ x >= z'), '! a != b\n& x < y\n|| x >= z');
assert.equal(pretty('result = Int64.of_int (Int32.to_int small)'), 'returned value == small');
assert.equal(pretty('gt_log_Int (Int64.to_int self_ + Int64.to_int rhs) (Int64.to_int const_MAX)'), '(self_ + rhs) > const_MAX');
assert.equal(pretty('forall r: Int64.t. result = Some r -> Int64.to_int r = Int64.to_int self_ + Int64.to_int rhs'), 'for every r:\n  returned value == ▣ r\n  implies r == self_ + rhs');
assert.equal(pretty('match result with | Malformed -> Int32.to_int partition_count <= 0 | Overflow -> gt_log_Int (Int32.to_int partition_count) 0 /\\ gt_log_Int (Int64.to_int total) (Int64.to_int const_MAX - Int32.to_int partition_count) end'), 'match returned value:\n  case Malformed:\n    partition_count <= 0\n  case Overflow:\n    partition_count > 0\n    & total > (const_MAX - partition_count)\nend');
assert.equal(pretty('match x with | Some y -> match y with | A -> true | B -> false end | None -> false end'), 'match x:\n  case ▣ y:\n    match y:\n      case A:\n        true\n      case B:\n        false\n    end\n  case □:\n    false\nend');
assert.equal(pretty('(forall r: Int64.t. result = Some r -> Int64.to_int r = 1) /\\ ready'), '(\n  for every r:\n    returned value == ▣ r\n    implies r == 1\n)\n& ready');
assert.equal(pretty('result = None'), 'returned value == □');
assert.equal(pretty('x = "result Some None"'), 'x == "result Some None"');
assert.equal(formulaTokens('result = Some r').map((token) => tokenText(token, false)).join(''), 'result = Some r');
assert.equal(pretty("Int64.to_int facts.consumed_at_ms <= 0"), 'facts.consumed_at_ms <= 0');
assert.equal(pretty("Int32.to_int result.limit_offset = Int64.to_int w.log_start"), 'returned value.limit_offset == w.log_start');
assert.equal(pretty("(result = Missing'0) = (facts.proposal = Missing)"), '(returned value == Missing\'0) == (facts.proposal == Missing)');
assert.equal(pretty("result = Some'0 r"), 'returned value == ▣ r');
assert.equal(pretty("match self_ with | Some'0 v -> result = Continue v | None'0 -> result = Break (None'1) end").replace(/\s+/g, ' '), 'match self_: case ▣ v: returned value == Continue v case □: returned value == Break (□) end');
assert.equal(formulaTokens("x'1 = 0").map((token) => tokenText(token, false)).join(''), "x'1 = 0");
assert.equal(formulaTokens("x'1 = 0").find((token) => token.text === '0').kind, 'literal');
console.log('Proof readability checks passed.');
